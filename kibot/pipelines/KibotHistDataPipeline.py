def parseEntryToCDF(file_name, extracted_path, target_date_only=None) -> list:
    #self._logger.info("PyRarFileManager::parseEntryToCDF(): - Parsing file: "+ name)
    cdf=[]
    symb = None
    base=os.path.basename(file_name)
    path=os.path.dirname(file_name)
    if re.match('[A-Z]*[0-9]*.[A-Z]*.txt',base):
        symb = base.replace('.txt', "")
        f_open = extracted_path  +"/" + base
        with open(f_open) as f:
            if target_date_only is not None:
                # Kibot lines start with MM/DD/YYYY,... — pre-filter at read time
                # so full-history refresh files (e.g. AAPL.txt = 4.2M lines) are
                # reduced to just the target date's lines (~390 rows). Avoids
                # ingesting the whole file into memory.
                prefix = target_date_only.strftime('%m/%d/%Y') + ','
                cdf = [parse(line, symb) for line in f if line.startswith(prefix)]
            else:
                cdf=[parse(line,symb) for line in f ]
    else:
             print("PyRarFileManager::parseEntryToCDF(): - Skipped File "+ file_name)
    return cdf, symb

