class KibotDailyFtpDump(BaseStage, AirflowStageMixin):
    """
        Downloads daily Kibot dumps from FTP and validates their presence.
        Can also be used as an AirflowStageMixin.
    """
    kibot_ftp_section = 'Kibot FTP'


    def run(self, ctx: PipelineContext) -> Tuple[StageResult, str]:
        errors : str = None
        outfolder = None
        ctx.logger.info('Starting Kibot Ftp Download with Params: '+ str(configparser_to_json(ctx.params)))
        skip_ftp = False
        try:
            skip_ftp = ctx.params.getboolean('default', 'skip_ftp', fallback=False)
        except Exception:
            skip_ftp = False

        try:
            outfolder  = ctx.params.get(self.kibot_ftp_section, 'outfolder')
            if skip_ftp:
                msg = 'Skipping FTP dump (skip_ftp=true) for KibotDailyFtpDump.'
                ctx.logger.info(msg)
                return (StageResult.SUCCESS, msg)
            ftp_params = FtpWrapperParameters(config_parser=ctx.params,
                                              ftp_section=self.kibot_ftp_section)
            ftp_worker = FtpWrapper(ftp_params,
                                    ctx.logger)
            os.makedirs(outfolder, exist_ok=True)
            ftp_worker.connect_to_ftp()
            # Skip Monthly/ — multi-GB archives our pipeline never consumes; they
            # would hang or timeout the daily FTP step.
            ftp_worker.dump_all_from_ftp('/Updates',
                                         outfolder,
                                         download_only_if_newer=True,
                                         verbose=True,
                                         exclude_dirs=['Monthly'])
        except Exception as e:
            errors = 'Error while running KibotDailyFtpDump ' + self.name + ': ' + str(e)
            ctx.logger.error(errors)

        if outfolder is None:
            return (StageResult.FAIL, 'Missing Kibot FTP configuration. errors: ' + str(errors))

        # Verify if the data was dumped
        rundate = datetime.strptime(
            ctx.params.get('default', 'rundate'), "%Y-%m-%d").date()
        prevdate = prev_business_day(rundate)
        yyyymmdd = prevdate.strftime('%Y%m%d')
        etf_daily_file = outfolder + '/All ETFs/Daily/' + str(yyyymmdd) +'.exe'
        stk_daily_file = outfolder + '/All Stocks/Daily/' + str(yyyymmdd) + '.exe'
        etf_daily_file_exists = os.path.exists(etf_daily_file)
        message = 'Etf file downloaded: ' + str(etf_daily_file_exists)
        stk_daily_file_exists = os.path.exists(stk_daily_file)
        message += '; Stock file downloaded: ' + str(stk_daily_file_exists)
        if stk_daily_file_exists and etf_daily_file_exists:
            if errors == '':
                stage = StageResult.SUCCESS
            else:
                stage = StageResult.SUCCESS_WITH_WARNINGS
        else:
            stage = StageResult.FAIL
        final_msg = message + '. errors: ' + str(errors)
        return (stage, final_msg)


class KibotDailyArchiveExtract(BaseStage, AirflowStageMixin):
    """
        Extracts daily archives once into a shared folder for reuse.
    """
    kibot_process_section = 'Kibot Cdf Processing'

    def run(self, ctx: PipelineContext) -> Tuple[StageResult, str]:
        try:
            shared_extract_root = ctx.params.get('default', 'shared_extract_root', fallback=None)
            if not shared_extract_root:
                msg = "No shared_extract_root configured; skipping archive extraction."
                ctx.logger.info(msg)
                return (StageResult.SUCCESS, msg)

            rundate = datetime.strptime(
                ctx.params.get('default', 'rundate'), "%Y-%m-%d").date()
            target_date = rundate - timedelta(days=1)
            ctx.logger.info(f"Archive extract rundate={rundate} target_date={target_date}")
            if target_date.weekday() >= 5:
                msg = f"Skipping archive extraction on weekend target_date {target_date}."
                ctx.logger.info(msg)
                return (StageResult.SUCCESS, msg)
            archives = set()
            stages_missing_summary = []

            def _collect_missing(params: ConfigParser, label: str) -> None:
                processing_stages = json.loads(params.get(self.kibot_process_section, 'processing_stages'))
                for stg in processing_stages:
                    stage_section = self.kibot_process_section + ' ' + stg
                    archivepath = params.get(stage_section, 'archivepath')
                    archive_in = archivepath + '/' + target_date.strftime('%Y%m%d') + '.exe'
                    processed_cdf_path = params.get(stage_section, 'processed_cdf_path')
                    summary_file = processed_cdf_path + '/processing_summary_' + target_date.strftime('%Y%m%d') + '.csv'
                    ctx.logger.info(
                        f"Summary check label={label} stage={stg} summary_file={summary_file} "
                        f"exists={os.path.exists(summary_file)}"
                    )
                    if os.path.exists(summary_file) and os.path.getsize(summary_file) > 0:
                        continue
                    stages_missing_summary.append(f"{label}:{stg}")
                    archives.add(archive_in)

            _collect_missing(ctx.params, "primary")
            extra_configs = ctx.params.get('default', 'extra_config_paths', fallback='')
            if extra_configs:
                for cfg_path in [p.strip() for p in extra_configs.split(',') if p.strip()]:
                    if not os.path.isfile(cfg_path):
                        ctx.logger.warning(f"Extra config not found: {cfg_path}")
                        continue
                    extra_params = ConfigParser()
                    extra_params.read(cfg_path)
                    if not extra_params.has_section(self.kibot_process_section):
                        ctx.logger.warning(f"Extra config missing section {self.kibot_process_section}: {cfg_path}")
                        continue
                    _collect_missing(extra_params, os.path.basename(cfg_path))

            if not stages_missing_summary:
                msg = "All processing summaries exist; skipping archive extraction."
                ctx.logger.info(msg)
                return (StageResult.SUCCESS, msg)

            # Pre-stage archives from NFS to local disk and extract in parallel.
            # NFS-bottlenecked sequential reads were the main extract cost.
            stage_root = tempfile.mkdtemp(prefix="kibot_stage_")
            ctx.logger.info(f"Staging archives locally under {stage_root}")
            try:
                def _stage_and_extract(archive_in: str) -> str:
                    archive_base = os.path.splitext(os.path.basename(archive_in))[0]
                    source_dir = _extract_subdir_from_archive(archive_in)
                    extract_path = os.path.join(shared_extract_root, source_dir, archive_base)
                    marker = os.path.join(extract_path, ".extracted")
                    if os.path.exists(marker):
                        return f"Archive already extracted: {archive_in}"
                    if not os.path.exists(archive_in):
                        raise FileNotFoundError(f"Archive missing: {archive_in}")
                    os.makedirs(extract_path, exist_ok=True)
                    # Stocks and ETFs archives share the same basename
                    # ("YYYYMMDD.exe"); keep them isolated by source_dir to avoid
                    # one thread's copy clobbering the other's.
                    stage_subdir = os.path.join(stage_root, source_dir)
                    os.makedirs(stage_subdir, exist_ok=True)
                    local_archive = os.path.join(stage_subdir, os.path.basename(archive_in))

                    # Copy from NFS to local with size verification + retry.
                    # Previously a silent NFS short-read or local-disk-full would
                    # produce a truncated local file and 7z would fail with
                    # cryptic "E_FAIL" or "No more files".
                    expected_size = os.path.getsize(archive_in)
                    last_err = None
                    for attempt in range(3):
                        try:
                            shutil.copyfile(archive_in, local_archive)
                            actual = os.path.getsize(local_archive)
                            if actual != expected_size:
                                raise IOError(
                                    f"copy size mismatch for {archive_in}: "
                                    f"src={expected_size} dst={actual} "
                                    f"(NFS short-read or local disk full?). "
                                    f"Free on stage dir: "
                                    f"{shutil.disk_usage(os.path.dirname(local_archive)).free} bytes"
                                )
                            last_err = None
                            break
                        except (OSError, IOError) as e:
                            last_err = e
                            try:
                                os.remove(local_archive)
                            except OSError:
                                pass
                            time.sleep(2 * (attempt + 1))
                    if last_err is not None:
                        raise last_err

                    try:
                        extract_with_7zip(local_archive, extract_path)
                    finally:
                        try:
                            os.remove(local_archive)
                        except OSError:
                            pass
                    with open(marker, "w") as handle:
                        handle.write(datetime.utcnow().isoformat())
                    return f"Extraction complete: {archive_in} -> {extract_path}"

                # 2 archives (stocks + ETFs) -> 2 worker threads is enough.
                with concurrent.futures.ThreadPoolExecutor(max_workers=max(1, len(archives))) as ex:
                    for fut in concurrent.futures.as_completed(
                        [ex.submit(_stage_and_extract, a) for a in archives]
                    ):
                        ctx.logger.info(fut.result())
            finally:
                shutil.rmtree(stage_root, ignore_errors=True)

            return (StageResult.SUCCESS, "Archive extraction complete.")
        except Exception as e:
            errors = 'Error while running KibotDailyArchiveExtract ' + self.name + ': ' + str(e)
            ctx.logger.error(errors)
            return (StageResult.FAIL, errors)


class KibotDailyArchiveCleanup(BaseStage, AirflowStageMixin):
    """
        Cleans up shared extracted archives after processing.
    """
    kibot_process_section = 'Kibot Cdf Processing'

    def run(self, ctx: PipelineContext) -> Tuple[StageResult, str]:
        try:
            if ctx.params.getboolean('default', 'skip_cleanup', fallback=False):
                msg = "skip_cleanup=true; leaving extracted archives in place."
                ctx.logger.info(msg)
                return (StageResult.SUCCESS, msg)
            shared_extract_root = ctx.params.get('default', 'shared_extract_root', fallback=None)
            if not shared_extract_root:
                msg = "No shared_extract_root configured; skipping archive cleanup."
                ctx.logger.info(msg)
                return (StageResult.SUCCESS, msg)

            rundate = datetime.strptime(
                ctx.params.get('default', 'rundate'), "%Y-%m-%d").date()
            target_date = rundate - timedelta(days=1)
            if target_date.weekday() >= 5:
                msg = f"Skipping archive cleanup on weekend target_date {target_date}."
                ctx.logger.info(msg)
                return (StageResult.SUCCESS, msg)
            processing_stages = json.loads(ctx.params.get(self.kibot_process_section, 'processing_stages'))
            archives = set()
            for stg in processing_stages:
                stage_section = self.kibot_process_section + ' ' + stg
                archivepath = ctx.params.get(stage_section, 'archivepath')
                archive_in = archivepath + '/' + target_date.strftime('%Y%m%d') + '.exe'
                archives.add(archive_in)

            for archive_in in archives:
                archive_base = os.path.splitext(os.path.basename(archive_in))[0]
                source_dir = _extract_subdir_from_archive(archive_in)
                extract_path = os.path.join(shared_extract_root, source_dir, archive_base)
                shutil.rmtree(extract_path, ignore_errors=True)
                ctx.logger.info(f"Cleaned extracted archive at {extract_path}")

            return (StageResult.SUCCESS, "Archive cleanup complete.")
        except Exception as e:
            errors = 'Error while running KibotDailyArchiveCleanup ' + self.name + ': ' + str(e)
            ctx.logger.error(errors)
            return (StageResult.FAIL, errors)



class KibotCdfProcessor(BaseStage, AirflowStageMixin):

    kibot_process_section = 'Kibot Cdf Processing'

    process_earliest_daily  : date = datetime.strptime('2016-01-01', '%Y-%m-%d').date()
    process_earliest_intra  : date = datetime.strptime('2019-01-01', '%Y-%m-%d').date()

    def _process_kibot_archive(self, archive_in: str,
                                     working_path: str,
                                     processed_cdf_path : str,
                                     daily : bool,
                                     logger: Logger = None,
                                     pre_extracted_path: str = None,
                                     cleanup: bool = True,
                                     target_date_only: date = None) -> (bool, str):
        yyyymmdd = extract_and_validate_date(archive_in)
        if yyyymmdd is None:
            return (False, 'The archive in could not be parsed to a valid date: ' + archive_in)
        try:
            # Create Historical Local Directory
            if pre_extracted_path and os.path.isdir(pre_extracted_path):
                working_path = pre_extracted_path
            if not os.path.exists(working_path): os.makedirs(working_path)
            count = 0
            try:
                if pre_extracted_path and os.path.isdir(pre_extracted_path):
                    logger.info("Using pre-extracted archive at " + working_path)
                else:
                    if not os.path.exists(archive_in):
                        return (False, f"Archive missing: {archive_in}")
                    extract_with_7zip(archive_in, working_path)
                outpath = processed_cdf_path + '/' + str(yyyymmdd)
                os.makedirs(outpath, exist_ok=True)
                # Parse the daily
                if daily:
                    fileToParse_Daily = os.listdir(working_path + "/Daily")
                    count = _parsing_and_writing_cdf(fileToParse_Daily,
                                                       working_path + "/Daily",
                                                       processed_cdf_path,
                                                       is_daily=True,
                                                       yyyymmdd=int(yyyymmdd),
                                                       processed_earliest_date=self.process_earliest_daily,
                                                       logger=logger,
                                                       target_date_only=target_date_only)

                else:
                    fileToParse_Intra = os.listdir(working_path + "/Intraday")
                    count = _parsing_and_writing_cdf(fileToParse_Intra,
                                                       working_path + "/Intraday",
                                                       processed_cdf_path,
                                                       is_daily=False,
                                                       yyyymmdd=int(yyyymmdd),
                                                       processed_earliest_date=self.process_earliest_intra,
                                                       logger=logger,
                                                       target_date_only=target_date_only)
            except Exception as e:
                print(f"Error extracting or parsing: {e}")
            finally:
                if cleanup:
                    shutil.rmtree(working_path, ignore_errors=True)
                pass
        except Exception as e:
            return (False, str(e))
        if count < 1500:
            return (False, f"Processed too few files ({count}) for {archive_in}")
        return (True, 'Processed: ' + str(count))


    def run(self, ctx: PipelineContext) -> Tuple[StageResult, str]:
        errors: str = None
        ctx.logger.info('Starting Kibot Cdf Processing with Params: ' + str(configparser_to_json(ctx.params)))

        try:
            processing_stages = json.loads(ctx.params.get(self.kibot_process_section, 'processing_stages'))
            stages_override = ctx.params.get('default', 'processing_stages_override', fallback=None)
            if stages_override:
                if isinstance(stages_override, (list, tuple)):
                    processing_stages = list(stages_override)
                else:
                    parsed = None
                    try:
                        parsed = json.loads(stages_override)
                    except Exception:
                        try:
                            parsed = ast.literal_eval(stages_override)
                        except Exception:
                            parsed = None
                    if isinstance(parsed, (list, tuple)):
                        processing_stages = [str(s).strip() for s in parsed]
                    elif isinstance(parsed, str):
                        processing_stages = [parsed.strip()]
                    else:
                        processing_stages = [s.strip() for s in str(stages_override).split(",") if s.strip()]
            rundate = datetime.strptime(
                        ctx.params.get('default', 'rundate'), "%Y-%m-%d").date()
            target_date = rundate - timedelta(days=1)
            if target_date.weekday() >= 5:
                msg = f"Skipping CDF processing on weekend target_date {target_date}."
                ctx.logger.info(msg)
                return (StageResult.SUCCESS, msg)
            shared_extract_root = ctx.params.get('default', 'shared_extract_root', fallback=None)
            # When rewrite_history is False (default), CDFs are written only for
            # target_date — preventing thousands of per-date NFS writes whenever
            # the archive contains a full-history refresh (AAPL/SPY/QQQ pattern).
            rewrite_history = ctx.params.getboolean('default', 'rewrite_history', fallback=False)
            target_date_only = None if rewrite_history else target_date
            ctx.logger.info(f"rewrite_history={rewrite_history} target_date_only={target_date_only}")
            success = True
            messages = []
            for stg in processing_stages:
                ctx.logger.info('Starting Stage: ' + str(stg))
                stage_section = self.kibot_process_section + ' ' + stg
                processed_cdf_path  = ctx.params.get(stage_section, 'processed_cdf_path')
                archivepath = ctx.params.get(stage_section, 'archivepath')
                workingfolder = ctx.params.get(stage_section, 'workingfolder')
                daily = ctx.params.getboolean(stage_section, 'daily')
                archive_in = archivepath + '/' + target_date.strftime('%Y%m%d') + '.exe'
                shared_extract_path = None
                if shared_extract_root:
                    archive_base = os.path.splitext(os.path.basename(archive_in))[0]
                    source_dir = _extract_subdir_from_archive(archive_in)
                    shared_extract_path = os.path.join(shared_extract_root, source_dir, archive_base)
                    workingfolder = shared_extract_path
                summary_file = processed_cdf_path + '/processing_summary_' + target_date.strftime('%Y%m%d') + '.csv'
                if os.path.exists(summary_file) and os.path.getsize(summary_file) > 0:
                    msg = f"Skipping stage {stg}; summary already exists: {summary_file}"
                    ctx.logger.info(msg)
                    continue

                msg = 'Processing archive_in: ' + archive_in + ', workingfolder: ' + workingfolder + ', daily: ' + str(daily)
                ctx.logger.info(msg)

                success_stg, message_stg = self._process_kibot_archive(archive_in,
                                                                   workingfolder,
                                                                   processed_cdf_path,
                                                                   daily,
                                                                   logger=ctx.logger,
                                                                   pre_extracted_path=shared_extract_path,
                                                                   cleanup=(shared_extract_root is None),
                                                                   target_date_only=target_date_only)
                success = success and success_stg
                messages.append(message_stg)

            if success:
                return (StageResult.SUCCESS, "; ".join(messages))
            else:
                return (StageResult.FAIL, "; ".join(messages))

        except Exception as e:
            errors = 'Error while running KibotDailyFtpDump ' + self.name + ': ' + str(e)
            ctx.logger.error(errors)
            return (StageResult.FAIL, "; ".join(messages) + ' -> '  + errors)
